use std::collections::BTreeMap;
use std::sync::OnceLock;

/// The table as a map, built once on first use. Duplicate keys would silently collapse, so the
/// lib tests reject them.
fn table() -> &'static BTreeMap<&'static str, &'static str> {
    static TABLE: OnceLock<BTreeMap<&'static str, &'static str>> = OnceLock::new();
    TABLE.get_or_init(|| ENTRIES.iter().copied().collect())
}

/// The 简体中文 translation of the English source string `s`, if it has one.
pub fn get(s: &str) -> Option<&'static str> {
    table().get(s).copied()
}

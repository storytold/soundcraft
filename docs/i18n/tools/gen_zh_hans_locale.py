#!/usr/bin/env python3
"""Generate `crates/ui-egui/locales/zh-Hans/mod.rs` from the translator-facing TSV.

The TSV (`crates/ui-egui/src/i18n/zh-hans.tsv`) is the source translators edit: one row per
string, `context<TAB>English source<TAB>Simplified Chinese`. The UI reads the Rust module, because
that is how every locale in this repository ships (see `locales/pt-BR/mod.rs`); this script is the
only thing that turns one into the other, so the two never drift.

Usage (from the repository root):

    python3 docs/i18n/tools/gen_zh_hans_locale.py           # write the module
    python3 docs/i18n/tools/gen_zh_hans_locale.py --check    # fail if it is out of date

`@plural` rows carry `singular|plural` in the source column, because English inflects where
Simplified Chinese does not; both English keys map to the same Chinese row. The columns use the
catalog's escapes (`\n`, `\t`, `\\`), which this script decodes before writing the Rust literal.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
TSV = ROOT / "crates/ui-egui/src/i18n/zh-hans.tsv"
OUT = ROOT / "crates/ui-egui/locales/zh-Hans/mod.rs"

HEADER = """\
//! Simplified Chinese (`zh-Hans`) catalog, keyed by the English source string.
//!
//! Generated by `docs/i18n/tools/gen_zh_hans_locale.py` from
//! `crates/ui-egui/src/i18n/zh-hans.tsv`; edit the TSV, then rerun the script. Engine diagnostics
//! stay English by design, so this catalog has no error templates.

/// Returns the Simplified Chinese translation for a source-language UI string.
#[rustfmt::skip]
pub(super) fn translate(source: &str) -> Option<&'static str> {
    Some(match source {
"""

FOOTER = """\
        _ => return None,
    })
}

/// Engine error messages with `{name}` placeholders standing for the values they embed. Simplified
/// Chinese keeps engine diagnostics in English by design (see `docs/localization-zh-hans.md`).
pub(super) const ERROR_TEMPLATES: &[(&str, &str)] = &[];
"""


def unescape(text: str) -> str:
    """Decode the catalog's `\\n`, `\\t` and `\\\\` escapes (the TSV is one row per string)."""
    out = []
    index = 0
    while index < len(text):
        ch = text[index]
        if ch == "\\" and index + 1 < len(text):
            nxt = text[index + 1]
            if nxt == "n":
                out.append("\n")
            elif nxt == "t":
                out.append("\t")
            elif nxt == "\\":
                out.append("\\")
            else:
                out.append(ch)
                out.append(nxt)
            index += 2
            continue
        out.append(ch)
        index += 1
    return "".join(out)


def rust_literal(text: str) -> str:
    """A Rust string literal for `text`; the catalogs contain quotes, braces and newlines."""
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def rows() -> dict[str, str]:
    """Every English source string mapped to its Chinese translation."""
    pairs: dict[str, str] = {}
    for number, line in enumerate(TSV.read_text(encoding="utf-8").splitlines(), start=1):
        if not line or line.startswith("#"):
            continue
        columns = line.split("\t", 2)
        if len(columns) != 3:
            raise SystemExit(f"{TSV}:{number}: expected three tab-separated columns")
        context, source, translation = (unescape(column) for column in columns)
        if not source or not translation:
            raise SystemExit(f"{TSV}:{number}: empty source or translation")
        # A `@plural` row names both English forms; Chinese has one form for both.
        sources = source.split("|") if context.startswith("@") else [source]
        for key in sources:
            previous = pairs.get(key)
            if previous is not None and previous != translation:
                raise SystemExit(f"{TSV}:{number}: {key!r} translated twice, differently")
            pairs[key] = translation
    return pairs


def render(pairs: dict[str, str]) -> str:
    arms = "".join(f"        {rust_literal(source)} => {rust_literal(pairs[source])},\n" for source in sorted(pairs))
    return HEADER + arms + FOOTER


def main(argv: list[str]) -> int:
    rendered = render(rows())
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != rendered:
            print(f"{OUT} is out of date; run python3 docs/i18n/tools/gen_zh_hans_locale.py", file=sys.stderr)
            return 1
        print(f"{OUT}: up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows())} strings)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))